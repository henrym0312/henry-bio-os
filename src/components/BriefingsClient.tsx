'use client';

import { Fragment, useState, useTransition } from 'react';
import { ChevronDown, ChevronRight, Loader2, Sparkles } from 'lucide-react';
import { triggerDiagnosticBriefingAction } from '@/app/actions';
import { cn } from '@/lib/utils';

export interface BriefingRow {
  id: number;
  periodStart: string;
  periodEnd: string;
  summaryMarkdown: string;
  metricsSnapshot: Record<string, unknown>;
  createdAt: string;
}

function renderInlineMarkdown(text: string) {
  const parts = text.split(/(\*\*[^*]+\*\*|`[^`]+`)/g);
  return parts.map((part, idx) => {
    if (part.startsWith('**') && part.endsWith('**')) {
      return (
        <strong key={idx} className="font-semibold text-[#F5F5F7]">
          {part.slice(2, -2)}
        </strong>
      );
    }
    if (part.startsWith('`') && part.endsWith('`')) {
      return (
        <code
          key={idx}
          className="px-1 py-0.5 rounded bg-[#1C1C1E] border border-white/[0.08] font-mono text-[11px] text-[#0A84FF]"
        >
          {part.slice(1, -1)}
        </code>
      );
    }
    return <Fragment key={idx}>{part}</Fragment>;
  });
}

function MarkdownDisplay({ markdown }: { markdown: string }) {
  const lines = markdown.split('\n');
  return (
    <div className="space-y-2 text-[13px] leading-relaxed text-[#D1D1D6]">
      {lines.map((rawLine, idx) => {
        const line = rawLine.trim();
        if (!line) {
          return <div key={idx} className="h-1" />;
        }
        if (line.startsWith('### ')) {
          return (
            <h4
              key={idx}
              className="text-xs font-semibold uppercase tracking-wider text-[#0A84FF] pt-2"
            >
              {renderInlineMarkdown(line.slice(4))}
            </h4>
          );
        }
        if (line.startsWith('## ')) {
          return (
            <h3
              key={idx}
              className="text-sm font-semibold text-[#F5F5F7] pt-3 pb-1 border-b border-white/[0.08]"
            >
              {renderInlineMarkdown(line.slice(3))}
            </h3>
          );
        }
        if (line.startsWith('# ')) {
          return (
            <h2 key={idx} className="text-base font-semibold text-[#F5F5F7] pt-2">
              {renderInlineMarkdown(line.slice(2))}
            </h2>
          );
        }
        if (line.startsWith('- ') || line.startsWith('* ')) {
          return (
            <div key={idx} className="flex items-start gap-2 pl-2">
              <span className="text-[#0A84FF] mt-1.5 w-1.5 h-1.5 rounded-full bg-[#0A84FF] shrink-0" />
              <span>{renderInlineMarkdown(line.slice(2))}</span>
            </div>
          );
        }
        if (/^\d+\.\s/.test(line)) {
          const match = /^(\d+)\.\s+(.*)$/.exec(line);
          if (match) {
            return (
              <div key={idx} className="flex items-start gap-2 pl-2">
                <span className="font-mono text-xs text-[#0A84FF] shrink-0 mt-0.5">
                  {match[1]}.
                </span>
                <span>{renderInlineMarkdown(match[2])}</span>
              </div>
            );
          }
        }
        return <p key={idx}>{renderInlineMarkdown(line)}</p>;
      })}
    </div>
  );
}

export function BriefingsClient({
  initialBriefings,
}: {
  initialBriefings: BriefingRow[];
}) {
  const [isPending, startTransition] = useTransition();
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [openSnapshots, setOpenSnapshots] = useState<Record<number, boolean>>({});

  const handleGenerate = () => {
    setErrorMsg(null);
    startTransition(async () => {
      const res = await triggerDiagnosticBriefingAction();
      if (!res.ok) {
        setErrorMsg(res.error);
      }
    });
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-xl font-semibold tracking-tight text-[#F5F5F7]">
            AI Diagnostic Briefings
          </h1>
          <p className="text-xs text-[#8E8E93] mt-0.5">
            Objective 7-day vs. 30-day physiological telemetry audits, Z-score strain alerts, and protocol recommendations generated by Gemini.
          </p>
        </div>

        <button
          type="button"
          onClick={handleGenerate}
          disabled={isPending}
          className="inline-flex items-center justify-center gap-2 px-4 py-2 rounded-lg bg-[#0A84FF] text-white text-xs font-medium hover:bg-[#0A84FF]/90 disabled:opacity-60 transition-colors cursor-pointer"
        >
          {isPending ? (
            <>
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
              Analysing Telemetry…
            </>
          ) : (
            <>
              <Sparkles className="w-3.5 h-3.5" />
              Generate Diagnostic Briefing
            </>
          )}
        </button>
      </div>

      {errorMsg && (
        <div className="rounded-xl bg-[#FF453A]/10 border border-[#FF453A]/40 p-4 text-xs text-[#FF453A]">
          {errorMsg}
        </div>
      )}

      {initialBriefings.length === 0 ? (
        <div className="rounded-xl bg-[#141416] border border-white/[0.08] p-10 text-center">
          <Sparkles className="w-8 h-8 text-[#0A84FF] mx-auto mb-3" />
          <h2 className="text-sm font-semibold text-[#F5F5F7]">
            No Diagnostic Briefings Generated Yet
          </h2>
          <p className="text-xs text-[#8E8E93] mt-1 max-w-md mx-auto">
            Click &ldquo;Generate Diagnostic Briefing&rdquo; above (or trigger `POST /api/analytics/briefing`) once biometric data is synced to receive an objective clinical protocol review.
          </p>
        </div>
      ) : (
        <div className="space-y-5">
          {initialBriefings.map((b, idx) => {
            const snapshotOpen = Boolean(openSnapshots[b.id]);
            const snap = b.metricsSnapshot as {
              anomalyReport?: { strainAlert?: boolean; adverseCount?: number };
              baselineComparison?: Array<{
                key: string;
                label: string;
                unit: string;
                mean7d: number | null;
                mean30d: number | null;
                delta7dVs30d: number | null;
              }>;
            };

            return (
              <article
                key={b.id}
                className={cn(
                  'rounded-xl bg-[#141416] border p-5 space-y-4',
                  idx === 0 ? 'border-[#0A84FF]/35' : 'border-white/[0.08]',
                )}
              >
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 pb-3 border-b border-white/[0.08]">
                  <div className="flex items-center gap-2.5">
                    <span className="text-xs font-mono tabular-nums px-2 py-0.5 rounded bg-[#0A84FF]/15 text-[#0A84FF]">
                      #{b.id}
                    </span>
                    <span className="text-sm font-semibold text-[#F5F5F7] font-mono tabular-nums">
                      {b.periodStart} → {b.periodEnd}
                    </span>
                    {snap?.anomalyReport?.strainAlert && (
                      <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-[#FF453A]/15 text-[#FF453A]">
                        Strain Alert Active
                      </span>
                    )}
                  </div>
                  <span className="text-xs font-mono tabular-nums text-[#8E8E93]">
                    Generated {b.createdAt.slice(0, 16).replace('T', ' ')} UTC
                  </span>
                </div>

                <MarkdownDisplay markdown={b.summaryMarkdown} />

                <div className="pt-2 border-t border-white/[0.08]">
                  <button
                    type="button"
                    onClick={() =>
                      setOpenSnapshots((prev) => ({
                        ...prev,
                        [b.id]: !prev[b.id],
                      }))
                    }
                    className="inline-flex items-center gap-1.5 text-xs font-mono text-[#8E8E93] hover:text-[#F5F5F7]"
                  >
                    {snapshotOpen ? (
                      <ChevronDown className="w-3.5 h-3.5" />
                    ) : (
                      <ChevronRight className="w-3.5 h-3.5" />
                    )}
                    Inspect 7d vs. 30d Telemetry Snapshot
                  </button>

                  {snapshotOpen && Array.isArray(snap?.baselineComparison) && (
                    <div className="mt-3 overflow-x-auto rounded-lg border border-white/[0.08] bg-[#0A0A0A]">
                      <table className="w-full text-left text-[11px] font-mono tabular-nums">
                        <thead>
                          <tr className="border-b border-white/[0.08] text-[#8E8E93]">
                            <th className="py-2 px-3">Metric</th>
                            <th className="py-2 px-3">7d Mean</th>
                            <th className="py-2 px-3">30d Baseline</th>
                            <th className="py-2 px-3">Delta</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-white/[0.06]">
                          {snap.baselineComparison.map((row) => (
                            <tr key={row.key}>
                              <td className="py-1.5 px-3 text-[#F5F5F7]">{row.label}</td>
                              <td className="py-1.5 px-3 text-[#F5F5F7]">
                                {row.mean7d !== null ? `${row.mean7d} ${row.unit}` : '—'}
                              </td>
                              <td className="py-1.5 px-3 text-[#8E8E93]">
                                {row.mean30d !== null ? `${row.mean30d} ${row.unit}` : '—'}
                              </td>
                              <td className="py-1.5 px-3 text-[#0A84FF]">
                                {row.delta7dVs30d !== null
                                  ? `${row.delta7dVs30d >= 0 ? '+' : ''}${row.delta7dVs30d}`
                                  : '—'}
                              </td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  )}
                </div>
              </article>
            );
          })}
        </div>
      )}
    </div>
  );
}
